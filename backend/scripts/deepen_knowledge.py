def main():
    changed = []
    for path in (Path(__file__).resolve().parents[1] / "data").glob("knowledge*.json"):
        articles = json.loads(path.read_text(encoding="utf-8"))
        dirty = False
        for article in articles:
            if article["id"] not in ADDITIONS:
                continue
            base = article["body"].split(MARKER)[0].rstrip()
            article["body"] = base + "\n\n" + "\n\n".join("## " + title + "\n" + body for title, body in ADDITIONS[article["id"]])
            article["updated_at"] = "2026-10-12"
            for ref in article.get("references", []):
                if ref["url"] in CHECKED:
                    ref["checked_at"] = "2026-10-12"
            if article["id"] == "cat-home":
                article["references"] = [r for r in article.get("references", []) if r["url"] != "https://catvets.com/wp-content/uploads/2026/07/FelineVMA-Step-by-Step-Guide-How-to-Introduce.pdf"] + [{"organization": "FelineVMA", "url": "https://catvets.com/wp-content/uploads/2026/07/FelineVMA-Step-by-Step-Guide-How-to-Introduce.pdf", "supports": "过渡区域、熟悉气味、按反应推进及资源安排；原环境指南页面本次遇访问校验，不伪称已重新读取", "version": "机构公开PDF，原发布日期未确认", "checked_at": "2026-10-12"}]
            changed.append(article["id"])
            dirty = True
        if dirty:
            path.write_text(json.dumps(articles, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Updated existing articles: " + ", ".join(sorted(changed)))


if __name__ == "__main__":
    main()
